namespace FuFramework.Utility.Extensions;

/// <summary>
/// 常量型变量的字节数
/// </summary>
public static class ConstSize
{
	/// <summary>
	/// 整型变量（32 位）的字节数。
	/// </summary>
	public const int IntSize = 4;

	/// <summary>
	/// 短整型变量（16 位）的字节数。
	/// </summary>
	public const int ShortSize = 2;

	/// <summary>
	/// 长整型变量（64 位）的字节数。
	/// </summary>
	public const int LongSize = 8;

	/// <summary>
	/// 单精度浮点型变量的字节数。
	/// </summary>
	public const int FloatSize = 4;

	/// <summary>
	/// 双精度浮点型变量的字节数。
	/// </summary>
	public const int DoubleSize = 8;

	/// <summary>
	/// 字节型变量（8 位）的字节数。
	/// </summary>
	public const int ByteSize = 1;

	/// <summary>
	/// 有符号字节类型变量的字节数。
	/// </summary>
	public const int SbyteSize = 1;

	/// <summary>
	/// 布尔型变量的字节数。
	/// </summary>
	public const int BoolSize = 1;

	/// <summary>
	/// 无符号整型变量（32 位）的字节数。
	/// </summary>
	public const int UIntSize = 4;

	/// <summary>
	/// 无符号短整型变量（16 位）的字节数。
	/// </summary>
	public const int UShortSize = 2;

	/// <summary>
	/// 无符号长整型变量（64 位）的字节数。
	/// </summary>
	public const int ULongSize = 8;
}
