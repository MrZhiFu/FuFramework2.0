using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace FuFramework.ProtoExport;

/// <summary>
/// 汇总生成 MessageIds.g.cs（生成物，勿手改）：模块号枚举 + 消息 ID 语义常量。
/// 常量值 = (module << 16) + opcode，行尾注释保留数值供脚本与人工速查。
/// </summary>
internal static class MessageIdsGenerator
{
    /// <summary>
    /// 全局唯一性校验：(module, opcode) 跨文件唯一；module 号与去号模块名每文件唯一。违反即报错中止。
    /// </summary>
    public static void ValidateGlobalUniqueness(List<MessageInfoList> messageInfoLists)
    {
        var opcodeOwners = new Dictionary<(int Module, int Opcode), (string File, string Message)>();
        var moduleOwners = new Dictionary<int, string>();
        var nameOwners = new HashSet<string>();
        foreach (var messageInfoList in messageInfoLists)
        {
            var moduleName = GetModuleName(messageInfoList.FileName);
            if (!moduleOwners.TryAdd(messageInfoList.Module, messageInfoList.FileName))
            {
                throw new Exception($"模块号 [{messageInfoList.Module}] 重复：{moduleOwners[messageInfoList.Module]} 与 {messageInfoList.FileName}");
            }

            if (!nameOwners.Add(moduleName))
            {
                throw new Exception($"模块名 [{moduleName}] 重复：{messageInfoList.FileName} 与其他文件去号后同名");
            }

            foreach (var operationCodeInfo in messageInfoList.Infos)
            {
                if (!operationCodeInfo.IsMessage)
                {
                    continue;
                }

                var key = (messageInfoList.Module, operationCodeInfo.Opcode);
                if (!opcodeOwners.TryAdd(key, (messageInfoList.FileName, operationCodeInfo.Name)))
                {
                    throw new Exception($"(module, opcode) [{messageInfoList.Module},{operationCodeInfo.Opcode}] 跨文件冲突：{opcodeOwners[key].File}/{opcodeOwners[key].Message} 与 {messageInfoList.FileName}/{operationCodeInfo.Name}");
                }
            }
        }
    }

    public static void Generate(List<MessageInfoList> messageInfoLists, string outputPath, string namespaceName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> 由 ProtoExport 生成，勿手改 </auto-generated>");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName}");
        sb.AppendLine("{");
        sb.AppendLine("\t/// <summary>模块号总表（与 proto 文件 option module 一一对应）</summary>");
        sb.AppendLine("\tpublic enum MessageModule");
        sb.AppendLine("\t{");
        foreach (var messageInfoList in messageInfoLists)
        {
            var moduleName = GetModuleName(messageInfoList.FileName);
            sb.AppendLine($"\t\t/// <summary>{messageInfoList.FileName}（module {messageInfoList.Module}）</summary>");
            sb.AppendLine($"\t\t{moduleName} = {messageInfoList.Module},");
        }

        sb.AppendLine("\t}");
        sb.AppendLine();
        sb.AppendLine("\t/// <summary>消息 ID 语义常量：ID = (module << 16) + opcode</summary>");
        sb.AppendLine("\tpublic static class MessageIds");
        sb.AppendLine("\t{");
        foreach (var messageInfoList in messageInfoLists)
        {
            var moduleName = GetModuleName(messageInfoList.FileName);
            var hasMessage = false;
            foreach (var operationCodeInfo in messageInfoList.Infos)
            {
                if (operationCodeInfo.IsMessage)
                {
                    hasMessage = true;
                    break;
                }
            }

            if (!hasMessage)
            {
                continue;
            }

            sb.AppendLine($"\t\tpublic static class {moduleName}   // module {messageInfoList.Module}");
            sb.AppendLine("\t\t{");
            foreach (var operationCodeInfo in messageInfoList.Infos)
            {
                if (!operationCodeInfo.IsMessage)
                {
                    continue;
                }

                var messageId = (messageInfoList.Module << 16) + operationCodeInfo.Opcode;
                sb.AppendLine($"\t\t\tpublic const int {operationCodeInfo.Name} = ((int)MessageModule.{moduleName} << 16) + {operationCodeInfo.Opcode}; // {messageId}");
            }

            sb.AppendLine("\t\t}");
        }

        sb.AppendLine("\t}");
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(outputPath, "MessageIds.g.cs"), sb.ToString(), Encoding.UTF8);
    }

    /// <summary>
    /// 生成 MessageIds.md 抓包速查表（生成物，勿手改）：按模块分组的 ID↔语义名对照，落在 proto 目录的上级（Protobuf/）。
    /// </summary>
    public static void GenerateLookupTable(List<MessageInfoList> messageInfoLists, string protoInputPath)
    {
        var protoDir = Path.GetFullPath(protoInputPath);
        var outputPath = Path.Combine(Path.GetDirectoryName(protoDir) ?? ".", "MessageIds.md");
        var sb = new StringBuilder();
        sb.AppendLine("# 消息 ID 速查表");
        sb.AppendLine();
        sb.AppendLine("> 由 ProtoExport 自动生成（勿手改）。消息 ID = (module << 16) + opcode。");
        sb.AppendLine();
        foreach (var messageInfoList in messageInfoLists)
        {
            sb.AppendLine($"## {GetModuleName(messageInfoList.FileName)}（module {messageInfoList.Module}）");
            sb.AppendLine();
            sb.AppendLine("| 消息名 | opcode | 完整 ID |");
            sb.AppendLine("|---|---|---|");
            foreach (var operationCodeInfo in messageInfoList.Infos)
            {
                if (!operationCodeInfo.IsMessage)
                {
                    continue;
                }

                sb.AppendLine($"| {operationCodeInfo.Name} | {operationCodeInfo.Opcode} | {(messageInfoList.Module << 16) + operationCodeInfo.Opcode} |");
            }

            sb.AppendLine();
        }

        sb.AppendLine("> 盲区：module 32766（short.MaxValue-1）段为服务器内置协议 DiscoveryCenter，手写维护，不在本表生成范围。");
        File.WriteAllText(outputPath, sb.ToString(), Encoding.UTF8);
    }

    /// <summary>模块名 = proto 文件名去掉末尾的 _模块号（User_300 → User，Inner_Basic_2 → Inner_Basic）。</summary>
    public static string GetModuleName(string fileName)
    {
        return Regex.Replace(fileName, @"_(\d+)$", "");
    }
}
