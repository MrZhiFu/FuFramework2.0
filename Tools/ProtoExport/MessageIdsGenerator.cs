using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace FuFramework.ProtoExport;

/// <summary>
/// 汇总生成 MessageIds.g.cs（生成物，勿手改）：模块号枚举 + 消息 ID 语义常量。
/// 常量值 = (module << 16) + opcode，行尾注释保留数值供脚本与人工速查。
/// </summary>
internal static class MessageIdsGenerator
{
    public static void Generate(List<MessageInfoList> messageInfoLists, string outputPath, string namespaceName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> 由 ProtoExport 生成，勿手改 </auto-generated>");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName}");
        sb.AppendLine("{");
        sb.AppendLine("\t/// <summary>模块号总表（与 proto 文件 option module 一一对应）</summary>");
        sb.AppendLine("\tpublic enum MessageModule");
        sb.AppendLine("\t{");
        foreach (var messageInfoList in messageInfoLists)
        {
            var moduleName = GetModuleName(messageInfoList.FileName);
            sb.AppendLine($"\t\t/// <summary>{messageInfoList.FileName}（module {messageInfoList.Module}）</summary>");
            sb.AppendLine($"\t\t{moduleName} = {messageInfoList.Module},");
        }

        sb.AppendLine("\t}");
        sb.AppendLine();
        sb.AppendLine("\t/// <summary>消息 ID 语义常量：ID = (module << 16) + opcode</summary>");
        sb.AppendLine("\tpublic static class MessageIds");
        sb.AppendLine("\t{");
        foreach (var messageInfoList in messageInfoLists)
        {
            var moduleName = GetModuleName(messageInfoList.FileName);
            var hasMessage = false;
            foreach (var operationCodeInfo in messageInfoList.Infos)
            {
                if (operationCodeInfo.IsMessage)
                {
                    hasMessage = true;
                    break;
                }
            }

            if (!hasMessage)
            {
                continue;
            }

            sb.AppendLine($"\t\tpublic static class {moduleName}   // module {messageInfoList.Module}");
            sb.AppendLine("\t\t{");
            foreach (var operationCodeInfo in messageInfoList.Infos)
            {
                if (!operationCodeInfo.IsMessage)
                {
                    continue;
                }

                var messageId = (messageInfoList.Module << 16) + operationCodeInfo.Opcode;
                sb.AppendLine($"\t\t\tpublic const int {operationCodeInfo.Name} = ((int)MessageModule.{moduleName} << 16) + {operationCodeInfo.Opcode}; // {messageId}");
            }

            sb.AppendLine("\t\t}");
        }

        sb.AppendLine("\t}");
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(outputPath, "MessageIds.g.cs"), sb.ToString(), Encoding.UTF8);
    }

    /// <summary>模块名 = proto 文件名去掉末尾的 _模块号（User_300 → User，Inner_Basic_2 → Inner_Basic）。</summary>
    public static string GetModuleName(string fileName)
    {
        return Regex.Replace(fileName, @"_(\d+)$", "");
    }
}
